const dicts: Record<Lang, Dict> = { uz, ru };

export function translate(lang: Lang, key: string, params?: Record<string, string | number>) {
  let s = dicts[lang][key] ?? dicts.uz[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.lang);
  return {
    lang,
    t: (key: string, params?: Record<string, string | number>) => translate(lang, key, params),
  };
}

export const errorKey = (code: string) => (dicts.uz[`err.${code}`] ? `err.${code}` : 'err.server_error');
